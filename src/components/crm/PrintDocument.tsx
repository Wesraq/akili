import type { ReactNode } from "react";

import logoLight from "@/assets/logo-akili.png";
import { cn } from "@/lib/utils";

export type PrintOrg = {
  orgName?: string;
  tagline?: string;
  address?: string;
  phone?: string;
  email?: string;
  footer?: string | undefined;
};

export function formatMoney(value: number, currency = "USD") {
  const code = (currency || "USD").trim().toUpperCase() || "USD";
  try {
    return new Intl.NumberFormat("en-US", {
      style: "currency",
      currency: code,
      maximumFractionDigits: 2,
    }).format(value);
  } catch {
    return `${code} ${value.toFixed(2)}`;
  }
}

export function PrintDocument({
  title,
  subtitle,
  meta,
  children,
  className,
  org,
}: {
  title: string;
  subtitle?: string;
  meta?: Array<{ label: string; value: string }>;
  children: ReactNode;
  className?: string;
  org?: PrintOrg;
}) {
  const orgName = org?.orgName || "AKILI LABS";
  const tagline = org?.tagline || "Clinical & equipment services";
  const location = [org?.address, org?.phone].filter(Boolean).join(" · ") || "Lusaka · Central & East Africa";
  const footer =
    org?.footer || `Generated by ${orgName} LIMS · ${new Date().toLocaleString()}`;

  return (
    <article
      className={cn(
        "mx-auto max-w-3xl bg-white text-black print:max-w-none",
        className,
      )}
    >
      <header className="border-b border-black/20 pb-4">
        <div className="flex flex-wrap items-start justify-between gap-4">
          <div className="flex items-start gap-3">
            <img
              src={logoLight}
              alt={orgName}
              width={48}
              height={48}
              className="size-12 object-contain"
            />
            <div>
              <p className="text-xs font-semibold tracking-[0.18em] uppercase">{orgName}</p>
              <h1 className="mt-2 text-2xl font-semibold tracking-tight">{title}</h1>
              {subtitle ? <p className="mt-1 text-sm text-black/70">{subtitle}</p> : null}
            </div>
          </div>
          <div className="text-right text-xs text-black/70">
            <p>{tagline}</p>
            <p>{location}</p>
            {org?.email ? <p>{org.email}</p> : null}
          </div>
        </div>
        {meta && meta.length > 0 ? (
          <dl className="mt-4 grid gap-2 text-sm sm:grid-cols-2">
            {meta.map((item) => (
              <div key={item.label}>
                <dt className="text-xs uppercase tracking-wide text-black/50">{item.label}</dt>
                <dd className="font-medium">{item.value}</dd>
              </div>
            ))}
          </dl>
        ) : null}
      </header>
      <div className="pt-5">{children}</div>
      <footer className="mt-10 border-t border-black/20 pt-3 text-xs text-black/60">{footer}</footer>
    </article>
  );
}
